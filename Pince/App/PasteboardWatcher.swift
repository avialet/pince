import AppKit
import PinceCore

/// Surveille le presse-papiers general et enregistre chaque nouvelle copie.
/// Ignore les copies marquees confidentielles ou transitoires (gestionnaires
/// de mots de passe) et celles venant des apps exclues.
@MainActor
final class PasteboardWatcher {
    static let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?
    /// Numero de changement produit par Pince lui-meme : ne pas le re-enregistrer.
    var ignoredChangeCount: Int?
    var excludedApps: Set<String> = []
    var onCapture: ((Capture, String?) -> Void)?

    enum Capture {
        case text(String)
        case files([URL])
        case image(Data)
    }

    init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        guard timer == nil else { return }
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.2
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        if count == ignoredChangeCount { return }
        let types = pasteboard.types ?? []
        if types.contains(where: { Self.concealedTypes.contains($0) }) { return }
        let source = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        if let source, excludedApps.contains(source) { return }
        guard let capture = read(types: types) else { return }
        onCapture?(capture, source)
    }

    private func read(types: [NSPasteboard.PasteboardType]) -> Capture? {
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return .files(urls)
        }
        if let text = pasteboard.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(text)
        }
        if types.contains(.png) || types.contains(.tiff), let image = NSImage(pasteboard: pasteboard),
           let tiff = image.tiffRepresentation, let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            return .image(png)
        }
        return nil
    }

    /// Remet un element dans le presse-papiers (sans le re-enregistrer).
    func write(_ item: ClipItem, imageURL: URL?) {
        pasteboard.clearContents()
        switch item.kind {
        case .files:
            pasteboard.writeObjects(item.fileURLs as [NSURL])
        case .image:
            if let imageURL, let image = NSImage(contentsOf: imageURL) {
                pasteboard.writeObjects([image])
            }
        default:
            pasteboard.setString(item.text ?? "", forType: .string)
        }
        ignoredChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
    }
}

/// Collage direct : simule ⌘V dans l'app au premier plan. Exige l'autorisation
/// d'accessibilite (Reglages Systeme > Confidentialite et securite > Accessibilite).
enum Paster {
    static var isTrusted: Bool { AXIsProcessTrusted() }

    /// Affiche la demande d'autorisation du systeme.
    @MainActor
    static func requestTrust() {
        let options = ["AXTrustedCheckOptionPrompt": true] as CFDictionary
        _ = AXIsProcessTrustedWithOptions(options)
    }

    @discardableResult
    static func simulatePaste() -> Bool {
        guard isTrusted, let source = CGEventSource(stateID: .combinedSessionState) else { return false }
        let keyV: CGKeyCode = 9
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: keyV, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: keyV, keyDown: false) else { return false }
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
        return true
    }
}
